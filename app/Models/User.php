<?php

namespace App\Models;

use Illuminate\Database\Eloquent\Factories\HasFactory;
use Illuminate\Database\Eloquent\Relations\BelongsTo;
use Illuminate\Database\Eloquent\Relations\HasMany;
use Illuminate\Database\Eloquent\SoftDeletes;
use Illuminate\Foundation\Auth\User as Authenticatable;
use Illuminate\Notifications\Notifiable;
use Laravel\Sanctum\HasApiTokens;
use Spatie\Permission\Traits\HasRoles;

class User extends Authenticatable
{
    use HasApiTokens, HasFactory, HasRoles, Notifiable, SoftDeletes;

    protected $fillable = [
        'name',
        'email',
        'password',
        'branch_id',
        'role_name',
        'engineer_code',
        'phone',
        'cash_balance',
        'zoho_petty_cash_account_id',
        'all_branches',
        'is_active',
    ];

    protected $hidden = [
        'password',
        'remember_token',
    ];

    protected function casts(): array
    {
        return [
            'email_verified_at' => 'datetime',
            'password' => 'hashed',
            'cash_balance' => 'decimal:2',
            'all_branches' => 'boolean',
            'is_active' => 'boolean',
        ];
    }

    /**
     * The primary branch of the user.
     */
    public function branch(): BelongsTo
    {
        return $this->belongsTo(Branch::class);
    }

    /**
     * Audit logs generated by this user.
     */
    public function auditLogs(): HasMany
    {
        return $this->hasMany(AuditLog::class);
    }

    /**
     * Check if user is Super Admin.
     */
    public function isSuperAdmin(): bool
    {
        return $this->role_name === 'super_admin' || $this->hasRole('super_admin');
    }

    /**
     * Check if user is Estimation.
     */
    public function isEstimation(): bool
    {
        return $this->role_name === 'estimation' || $this->hasRole('estimation');
    }

    /**
     * Check if user is Project Engineer.
     */
    public function isEngineer(): bool
    {
        return $this->role_name === 'engineer' || $this->hasRole('engineer');
    }

    /**
     * Check if user is Accountant.
     */
    public function isAccountant(): bool
    {
        return $this->role_name === 'accountant' || $this->hasRole('accountant');
    }

    /**
     * Check if user can access a specific branch.
     */
    public function canAccessBranch(int|string|null $branchId): bool
    {
        if ($this->all_branches || $this->isSuperAdmin() || $this->isAccountant()) {
            return true;
        }

        if (empty($branchId) || $branchId === 'all') {
            return true;
        }

        return (int) $this->branch_id === (int) $branchId;
    }

    /**
     * User initials (e.g. John Doe -> JD)
     */
    public function getInitialsAttribute(): string
    {
        $words = preg_split('/\s+/', trim($this->name));
        $initials = '';
        foreach (array_slice($words, 0, 2) as $w) {
            $initials .= strtoupper($w[0] ?? '');
        }
        return $initials ?: 'RM';
    }

    /**
     * Human readable role label
     */
    public function getRoleLabelAttribute(): string
    {
        return match ($this->role_name) {
            'super_admin' => 'Super Admin',
            'estimation' => 'Estimation User',
            'engineer' => 'Project Engineer',
            'accountant' => 'Accountant',
            default => ucfirst(str_replace('_', ' ', $this->role_name)),
        };
    }
}
